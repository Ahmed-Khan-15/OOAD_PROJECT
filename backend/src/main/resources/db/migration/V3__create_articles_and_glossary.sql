-- Editorial content is stored separately from the reference catalogue and health observations.

CREATE TABLE article_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL UNIQUE,
    display_order INTEGER NOT NULL DEFAULT 0
);

INSERT INTO article_categories (slug, name, display_order) VALUES
    ('health-explainers', 'Health Explainers', 1),
    ('global-health-insights', 'Global Health Insights', 2),
    ('research-summaries', 'Research Summaries', 3),
    ('data-stories', 'Data Stories', 4);

CREATE TABLE articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES article_categories(id) ON DELETE RESTRICT,
    title VARCHAR(240) NOT NULL,
    subtitle VARCHAR(400),
    slug VARCHAR(240) NOT NULL UNIQUE,
    cover_image_url TEXT,
    author_name VARCHAR(180) NOT NULL,
    introduction TEXT,
    content TEXT,
    reading_minutes INTEGER,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT articles_status_check CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT articles_reading_minutes_check CHECK (reading_minutes IS NULL OR reading_minutes > 0),
    CONSTRAINT articles_not_blank_check CHECK (length(trim(title)) > 0 AND length(trim(author_name)) > 0)
);

CREATE INDEX idx_articles_public_listing ON articles (category_id, published_at DESC, id)
    WHERE status = 'PUBLISHED';
CREATE INDEX idx_articles_status_updated ON articles (status, updated_at DESC);

CREATE TABLE article_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE article_tag_links (
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES article_tags(id) ON DELETE CASCADE,
    PRIMARY KEY (article_id, tag_id)
);
CREATE INDEX idx_article_tag_links_tag ON article_tag_links (tag_id, article_id);

CREATE TABLE article_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL DEFAULT 0,
    label VARCHAR(300) NOT NULL,
    url TEXT NOT NULL,
    CONSTRAINT article_reference_label_not_blank CHECK (length(trim(label)) > 0)
);
CREATE INDEX idx_article_references_article ON article_references (article_id, display_order, id);

CREATE TABLE article_related_articles (
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    related_article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    PRIMARY KEY (article_id, related_article_id),
    CONSTRAINT article_related_not_self CHECK (article_id <> related_article_id)
);

CREATE TABLE article_topics (
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE RESTRICT,
    PRIMARY KEY (article_id, topic_id)
);
CREATE TABLE article_countries (
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    country_id BIGINT NOT NULL REFERENCES countries(id) ON DELETE RESTRICT,
    PRIMARY KEY (article_id, country_id)
);
CREATE TABLE article_indicators (
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    indicator_id BIGINT NOT NULL REFERENCES indicators(id) ON DELETE RESTRICT,
    PRIMARY KEY (article_id, indicator_id)
);
CREATE INDEX idx_article_topics_topic ON article_topics (topic_id, article_id);
CREATE INDEX idx_article_countries_country ON article_countries (country_id, article_id);
CREATE INDEX idx_article_indicators_indicator ON article_indicators (indicator_id, article_id);

CREATE TABLE glossary_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    definition TEXT NOT NULL,
    extended_explanation TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT glossary_term_not_blank CHECK (length(trim(term)) > 0 AND length(trim(definition)) > 0)
);
CREATE INDEX idx_glossary_terms_name ON glossary_terms (lower(term));

CREATE TABLE glossary_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    glossary_term_id BIGINT NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL DEFAULT 0,
    label VARCHAR(300) NOT NULL,
    url TEXT NOT NULL,
    CONSTRAINT glossary_reference_label_not_blank CHECK (length(trim(label)) > 0)
);
CREATE INDEX idx_glossary_references_term ON glossary_references (glossary_term_id, display_order, id);

CREATE TABLE glossary_related_terms (
    term_id BIGINT NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    related_term_id BIGINT NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    PRIMARY KEY (term_id, related_term_id),
    CONSTRAINT glossary_related_not_self CHECK (term_id <> related_term_id)
);
CREATE TABLE glossary_articles (
    glossary_term_id BIGINT NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    PRIMARY KEY (glossary_term_id, article_id)
);
CREATE TABLE glossary_topics (
    glossary_term_id BIGINT NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE RESTRICT,
    PRIMARY KEY (glossary_term_id, topic_id)
);
CREATE TABLE glossary_indicators (
    glossary_term_id BIGINT NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    indicator_id BIGINT NOT NULL REFERENCES indicators(id) ON DELETE RESTRICT,
    PRIMARY KEY (glossary_term_id, indicator_id)
);
CREATE INDEX idx_glossary_articles_article ON glossary_articles (article_id, glossary_term_id);
CREATE INDEX idx_glossary_topics_topic ON glossary_topics (topic_id, glossary_term_id);
CREATE INDEX idx_glossary_indicators_indicator ON glossary_indicators (indicator_id, glossary_term_id);
