CREATE TABLE donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(40) NOT NULL UNIQUE,
    donor_name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    frequency VARCHAR(12) NOT NULL,
    anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(24) NOT NULL DEFAULT 'SIMULATED_SUCCESS',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT donation_amount_range CHECK (amount >= 1 AND amount <= 10000),
    CONSTRAINT donation_frequency_check CHECK (frequency IN ('ONCE', 'MONTHLY')),
    CONSTRAINT donation_status_check CHECK (status IN ('SIMULATED_SUCCESS')),
    CONSTRAINT donation_name_not_blank CHECK (length(trim(donor_name)) > 0)
);

CREATE INDEX idx_donations_created_at ON donations (created_at DESC);
CREATE INDEX idx_donations_frequency_status ON donations (frequency, status);
