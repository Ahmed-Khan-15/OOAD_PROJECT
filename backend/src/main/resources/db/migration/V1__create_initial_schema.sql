-- Global Health Explorer: initial relational schema
-- PostgreSQL 18 | Managed by Flyway
-- Missing observations are represented by absence of a row, never by a zero value.

CREATE TABLE countries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    iso2 CHAR(2) NOT NULL UNIQUE,
    iso3 CHAR(3) NOT NULL UNIQUE,
    region VARCHAR(80),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT countries_name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE TABLE country_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id BIGINT NOT NULL REFERENCES countries(id) ON DELETE RESTRICT,
    data_source_id BIGINT,
    alias VARCHAR(160) NOT NULL,
    alias_normalized VARCHAR(160) NOT NULL,
    alias_type VARCHAR(30) NOT NULL DEFAULT 'SOURCE_NAME',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT country_aliases_type_check
        CHECK (alias_type IN ('SOURCE_NAME', 'ISO2', 'ISO3', 'OTHER'))
);

CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    slug VARCHAR(140) NOT NULL UNIQUE,
    description TEXT,
    is_overview BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE indicators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE RESTRICT,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    description TEXT,
    unit VARCHAR(100) NOT NULL,
    preferred_direction VARCHAR(20) NOT NULL DEFAULT 'NEUTRAL',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT indicators_topic_name_unique UNIQUE (topic_id, name),
    CONSTRAINT indicators_direction_check
        CHECK (preferred_direction IN ('LOWER', 'HIGHER', 'NEUTRAL'))
);

CREATE TABLE data_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL UNIQUE,
    abbreviation VARCHAR(40),
    website_url TEXT,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE country_aliases
    ADD CONSTRAINT country_aliases_data_source_fk
    FOREIGN KEY (data_source_id) REFERENCES data_sources(id) ON DELETE RESTRICT;

CREATE TABLE datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_source_id BIGINT NOT NULL REFERENCES data_sources(id) ON DELETE RESTRICT,
    name VARCHAR(220) NOT NULL,
    slug VARCHAR(240) NOT NULL UNIQUE,
    description TEXT,
    source_url TEXT,
    citation TEXT,
    license_name VARCHAR(180),
    license_url TEXT,
    methodology TEXT,
    frequency VARCHAR(40),
    published_at DATE,
    coverage_start_year INTEGER,
    coverage_end_year INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT datasets_year_range_check CHECK (
        coverage_start_year IS NULL OR coverage_end_year IS NULL
        OR coverage_start_year <= coverage_end_year
    )
);

CREATE TABLE indicator_source_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
    indicator_id BIGINT NOT NULL REFERENCES indicators(id) ON DELETE RESTRICT,
    original_indicator_code VARCHAR(180),
    original_indicator_name VARCHAR(240) NOT NULL,
    original_unit VARCHAR(120),
    conversion_notes TEXT,
    dimensions_description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT indicator_source_mapping_unique
        UNIQUE (dataset_id, original_indicator_code, indicator_id)
);

CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT admin_email_not_blank CHECK (length(trim(email)) > 0)
);

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
    initiated_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
    import_method VARCHAR(20) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    original_filename VARCHAR(255),
    file_checksum VARCHAR(128),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    total_rows INTEGER NOT NULL DEFAULT 0,
    accepted_rows INTEGER NOT NULL DEFAULT 0,
    rejected_rows INTEGER NOT NULL DEFAULT 0,
    duplicate_rows INTEGER NOT NULL DEFAULT 0,
    summary TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT import_method_check CHECK (import_method IN ('ADMIN_CSV', 'BUNDLED_DATASET')),
    CONSTRAINT import_status_check CHECK (
        status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED')
    ),
    CONSTRAINT import_counts_nonnegative CHECK (
        total_rows >= 0 AND accepted_rows >= 0 AND rejected_rows >= 0 AND duplicate_rows >= 0
    )
);

CREATE TABLE import_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_batch_id BIGINT NOT NULL REFERENCES import_batches(id) ON DELETE CASCADE,
    row_number INTEGER,
    error_code VARCHAR(80),
    error_message TEXT NOT NULL,
    raw_row JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE health_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id BIGINT NOT NULL REFERENCES countries(id) ON DELETE RESTRICT,
    indicator_id BIGINT NOT NULL REFERENCES indicators(id) ON DELETE RESTRICT,
    dataset_id BIGINT NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
    source_mapping_id BIGINT REFERENCES indicator_source_mappings(id) ON DELETE RESTRICT,
    import_batch_id BIGINT REFERENCES import_batches(id) ON DELETE SET NULL,
    reference_year INTEGER NOT NULL,
    value NUMERIC(22, 8) NOT NULL,
    dimensions JSONB NOT NULL DEFAULT '{}'::jsonb,
    value_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    uncertainty_lower NUMERIC(22, 8),
    uncertainty_upper NUMERIC(22, 8),
    original_value_text VARCHAR(160),
    observation_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT health_observation_status_check CHECK (
        value_status IN ('REPORTED', 'ESTIMATED', 'MODELLED', 'PROJECTED', 'UNKNOWN')
    ),
    CONSTRAINT health_observation_uncertainty_check CHECK (
        (uncertainty_lower IS NULL OR uncertainty_lower <= value)
        AND (uncertainty_upper IS NULL OR uncertainty_upper >= value)
        AND (uncertainty_lower IS NULL OR uncertainty_upper IS NULL
             OR uncertainty_lower <= uncertainty_upper)
    ),
    CONSTRAINT health_observation_identity_unique
        UNIQUE (country_id, indicator_id, dataset_id, reference_year, dimensions)
);

CREATE INDEX idx_health_observations_country_indicator_year
    ON health_observations (country_id, indicator_id, reference_year);

CREATE INDEX idx_health_observations_indicator_year
    ON health_observations (indicator_id, reference_year);

CREATE INDEX idx_health_observations_dataset
    ON health_observations (dataset_id);

CREATE INDEX idx_health_observations_dimensions
    ON health_observations USING GIN (dimensions);

CREATE INDEX idx_import_batches_dataset_created
    ON import_batches (dataset_id, created_at DESC);

CREATE INDEX idx_import_errors_batch
    ON import_errors (import_batch_id);

CREATE UNIQUE INDEX uq_country_alias_source_normalized
    ON country_aliases (COALESCE(data_source_id, 0), alias_normalized);

-- Prevent the same original code from being mapped repeatedly within a dataset.
CREATE UNIQUE INDEX uq_mapping_dataset_code_indicator
    ON indicator_source_mappings (dataset_id, COALESCE(original_indicator_code, ''), indicator_id);
